// alert-broken-chains.js — Creates GitHub Issues for chains returning HTTP 404
// Usage: GITHUB_TOKEN=... node alert-broken-chains.js
// Called by deal-update.yml after deal verification
// Only triggers for classification === '404' (NOT 403, NOT timeout, NOT meta_verified)
// Always exits 0 — never fails the pipeline

'use strict';

const https = require('https');
const fs    = require('fs');
const path  = require('path');

const REPO     = 'Carlos-bot-43/freebieme';
const API_BASE = 'api.github.com';
const TODAY    = new Date().toISOString().slice(0, 10);
const TOKEN    = process.env.GITHUB_TOKEN || '';

const DATA_DIR   = path.join(__dirname, 'data');
const VERIFY_FILE = path.join(DATA_DIR, 'output', `deal-verification-${TODAY}.json`);

function readJSON(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (e) { return null; }
}

// GitHub API request helper
function ghRequest(method, urlPath, body) {
  return new Promise((resolve, reject) => {
    if (!TOKEN) return reject(new Error('GITHUB_TOKEN not set'));
    const payload = body ? JSON.stringify(body) : null;
    const req = https.request({
      hostname: API_BASE,
      path:     urlPath,
      method,
      headers: {
        'Authorization':  `Bearer ${TOKEN}`,
        'Accept':         'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent':     'FreebieMe-Alert-Bot/1.0',
        ...(payload && { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(payload) }),
      },
    }, (res) => {
      const chunks = [];
      res.on('data', c => chunks.push(c));
      res.on('end', () => {
        const text = chunks.join('');
        try { resolve({ status: res.statusCode, data: JSON.parse(text) }); }
        catch (e) { resolve({ status: res.statusCode, data: text }); }
      });
    });
    req.on('error', reject);
    if (payload) req.write(payload);
    req.end();
  });
}

// Ensure the "deal-maintenance" label exists (creates it if not)
async function ensureLabel() {
  const labelName  = 'deal-maintenance';
  const labelColor = 'e4e669';
  // Check if label exists
  const res = await ghRequest('GET', `/repos/${REPO}/labels/${encodeURIComponent(labelName)}`);
  if (res.status === 200) return; // Already exists
  if (res.status === 404) {
    // Create it
    await ghRequest('POST', `/repos/${REPO}/labels`, {
      name:  labelName,
      color: labelColor,
      description: 'Issues needing deal URL maintenance',
    });
    console.log(`Created label: ${labelName}`);
  }
}

// Check for existing open issues with the same date to avoid duplicates
async function hasExistingIssue(titlePattern) {
  const res = await ghRequest('GET', `/repos/${REPO}/issues?state=open&labels=deal-maintenance&per_page=20`);
  if (res.status !== 200 || !Array.isArray(res.data)) return false;
  return res.data.some(issue => issue.title && issue.title.includes(titlePattern));
}

// Create a GitHub issue for broken 404 chains
async function createIssue(broken404Chains) {
  const title = `⚠️ FreebieMe: Broken chain URLs detected [${TODAY}]`;

  // Skip if same-day issue already exists
  const alreadyExists = await hasExistingIssue(TODAY);
  if (alreadyExists) {
    console.log(`Issue for ${TODAY} already exists — skipping duplicate`);
    return;
  }

  const body = [
    `## FreebieMe: ${broken404Chains.length} Chain URL(s) Returning 404`,
    '',
    `**Detected on:** ${TODAY}`,
    '',
    'The following chains\' reward page URLs returned HTTP 404 during the daily deal verification.',
    'These are **real problems** that need URL updates — not bot-blocking (403) or timeouts.',
    '',
    '### Broken URLs',
    '',
    '| Chain | Broken URL | Suggested Fix |',
    '|-------|-----------|---------------|',
    ...broken404Chains.map(([slug, r]) =>
      `| \`${slug}\` | \`${r.url}\` | Find new rewards URL on their site |`
    ),
    '',
    '### How to Fix',
    '',
    '1. Visit the chain\'s website and find their current rewards/loyalty page URL',
    '2. Update the URL in `verify-deals.js` in the `CHAIN_VERIFICATIONS` object',
    '3. Run `node verify-deals.js` locally to confirm the new URL works',
    '4. Commit and push the fix',
    '',
    '---',
    '*Generated by alert-broken-chains.js | FreebieMe Daily Deal Update*',
  ].join('\n');

  await ensureLabel();

  const res = await ghRequest('POST', `/repos/${REPO}/issues`, {
    title,
    body,
    labels: ['deal-maintenance'],
  });

  if (res.status === 201) {
    console.log(`✅ GitHub Issue created: ${res.data.html_url}`);
  } else {
    console.warn(`GitHub Issue creation returned status ${res.status}:`, JSON.stringify(res.data).slice(0, 200));
  }
}

async function main() {
  // Load verification report
  const report = readJSON(VERIFY_FILE);
  if (!report) {
    console.log(`alert-broken-chains: No verification report found at ${VERIFY_FILE} — skipping`);
    return;
  }

  // Find only TRUE 404s (not 403, not timeout, not content warnings)
  const chains = report.chains || {};
  const broken404Chains = Object.entries(chains)
    .filter(([, r]) => r.classification === '404');

  if (broken404Chains.length === 0) {
    console.log(`✅ alert-broken-chains: No broken 404s found — no GitHub issue needed`);
    return;
  }

  console.log(`⚠️ alert-broken-chains: ${broken404Chains.length} chain(s) returning 404:`);
  broken404Chains.forEach(([slug, r]) => console.log(`  ${slug}: ${r.url}`));

  if (!TOKEN) {
    console.warn('alert-broken-chains: GITHUB_TOKEN not set — cannot create issue. Fix these chains:');
    broken404Chains.forEach(([slug, r]) => console.warn(`  ${slug}: ${r.url}`));
    return;
  }

  await createIssue(broken404Chains);
}

main().catch(e => {
  console.error('alert-broken-chains.js: non-fatal error:', e.message);
  // Always exit 0 — never fail the pipeline
}).finally(() => {
  process.exit(0);
});
